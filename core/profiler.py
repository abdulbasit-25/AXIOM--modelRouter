"""
core/profiler.py

Dev Mode calibration engine that benchmarks supported models against reference rubrics.
Calculates text similarity, format adherence, and latency scores to compute a composite
benchmark score, maintaining a CapabilityMatrix of winning architectures per tier.
"""

from __future__ import annotations

import difflib
import math
import re
from typing import Any


class CapabilityMatrix:
    """
    Capability matrix mapping model routing tiers to calibrated winning model architectures.

    Default recommendations use models already configured in the production model client.
    """

    DEFAULT_ARCHITECTURES: dict[int, dict[str, str]] = {
        1: {
            "model": "openai/gpt-oss-20b",
            "provider": "OpenAI via Groq",
            "tier_name": "Tier 1 (Instant / Low-Latency)",
        },
        2: {
            "model": "qwen/qwen3.8-27b",
            "provider": "Alibaba via Groq",
            "tier_name": "Tier 2 (Balanced / Reasoning)",
        },
        3: {
            "model": "openai/gpt-oss-120b",
            "provider": "OpenAI via Groq",
            "tier_name": "Tier 3 (Heavy / Complex Synthesis)",
        },
    }

    def __init__(self, initial_matrix: dict[int, str] | None = None) -> None:
        self._matrix: dict[int, str] = {
            tier: metadata["model"]
            for tier, metadata in self.DEFAULT_ARCHITECTURES.items()
        }
        self._metadata: dict[int, dict[str, str]] = {
            k: dict(v) for k, v in self.DEFAULT_ARCHITECTURES.items()
        }
        if initial_matrix:
            for tier, model in initial_matrix.items():
                self.update_matrix(tier, model)

    def get_model(self, tier: int) -> str:
        """Get the current winning model architecture for a given tier."""
        if tier not in self._matrix:
            raise KeyError(f"Unknown tier: {tier}. Available tiers: {list(self._matrix.keys())}")
        return self._matrix[tier]

    def update_matrix(self, tier: int, best_model: str) -> None:
        """
        Update the winning model architecture for a specified tier.

        Args:
            tier: The model routing tier (1, 2, or 3).
            best_model: The model identifier string.
        """
        if tier not in self.DEFAULT_ARCHITECTURES:
            raise ValueError(f"Unknown tier: {tier}. Expected a tier from 1 to 3.")
        if not best_model or not best_model.strip():
            raise ValueError("A non-empty model identifier is required.")

        self._matrix[tier] = best_model.strip()
        if tier not in self._metadata:
            self._metadata[tier] = {
                "model": best_model.strip(),
                "provider": "Custom",
                "tier_name": f"Tier {tier}",
            }
        else:
            self._metadata[tier]["model"] = best_model

    def to_dict(self) -> dict[int, str]:
        """Return a mapping dictionary of {tier: model_name}."""
        return dict(self._matrix)

    def get_metadata(self, tier: int) -> dict[str, str]:
        """Return provider and tier metadata for a given tier."""
        return dict(self._metadata.get(tier, {}))

    def __getitem__(self, tier: int) -> str:
        return self.get_model(tier)

    def __setitem__(self, tier: int, best_model: str) -> None:
        self.update_matrix(tier, best_model)

    def __repr__(self) -> str:
        return f"CapabilityMatrix({self._matrix})"


class BenchmarkProfiler:
    """
    Dev Mode calibration engine that benchmarks model responses against reference rubrics
    using lexical text similarity, format conformity, and latency metrics.
    """

    def __init__(
        self,
        capability_matrix: CapabilityMatrix | None = None,
        max_latency_ms: float = 2000.0,
    ) -> None:
        """
        Initialize the BenchmarkProfiler.

        Args:
            capability_matrix: Optional custom CapabilityMatrix instance.
            max_latency_ms: Reference latency baseline for speed score normalization.
        """
        self.capability_matrix = capability_matrix or CapabilityMatrix()
        if not math.isfinite(max_latency_ms) or max_latency_ms <= 0:
            raise ValueError("max_latency_ms must be a finite number greater than zero.")
        self.max_latency_ms = max_latency_ms

    def evaluate_response(
        self,
        candidate_output: str = "",
        ground_truth: str = "",
        latency_ms: float = 0.0,
        cost: float = 0.0,
    ) -> dict[str, Any]:
        """
        Evaluate a candidate model output against a ground-truth rubric.

        Args:
            candidate_output: Output text generated by the candidate model.
            ground_truth: Reference text / ground-truth rubric.
            latency_ms: Response latency in milliseconds.
            cost: Generation cost in USD.

        Returns:
            Structured dictionary of evaluation metrics:
              - semantic_score (float): Character-level text similarity (0.0 to 1.0).
              - token_overlap_score (float): Token-level Jaccard similarity.
              - content_score (float): Mean of the two reference similarity metrics.
              - format_score (float): Markdown structure adherence (0.5 or 1.0).
              - speed_score (float): Latency-derived speed score (0.0 to 1.0).
              - composite_score (float): (0.6 * semantic) + (0.2 * format) + (0.2 * speed).
              - latency_ms (float): Execution latency in milliseconds.
              - cost (float): Cost in USD.
        """
        # Allow class-level invocation BenchmarkProfiler.evaluate_response(...)
        if not isinstance(self, BenchmarkProfiler):
            return BenchmarkProfiler().evaluate_response(
                candidate_output=self if isinstance(self, str) else candidate_output,
                ground_truth=candidate_output if isinstance(self, str) else ground_truth,
                latency_ms=ground_truth if isinstance(ground_truth, (int, float)) else latency_ms,
                cost=latency_ms if isinstance(latency_ms, (int, float)) else cost,
            )

        if not ground_truth or not ground_truth.strip():
            raise ValueError("A non-empty ground-truth answer or rubric is required.")
        if not math.isfinite(latency_ms) or latency_ms < 0:
            raise ValueError("latency_ms must be a finite non-negative number.")
        if not math.isfinite(cost) or cost < 0:
            raise ValueError("cost must be a finite non-negative number.")

        # Text similarity is lexical, not a claim of factual or semantic correctness.
        semantic_score = self.calculate_semantic_score(candidate_output, ground_truth)
        token_overlap_score = self.calculate_token_overlap(candidate_output, ground_truth)
        content_score = round((semantic_score + token_overlap_score) / 2, 4)

        format_score = self.calculate_format_score(candidate_output, ground_truth)
        speed_score = self.calculate_speed_score(latency_ms)
        composite_score = round(
            (0.6 * content_score) + (0.2 * format_score) + (0.2 * speed_score),
            4,
        )

        return {
            "semantic_score": semantic_score,
            "token_overlap_score": token_overlap_score,
            "content_score": content_score,
            "format_score": format_score,
            "speed_score": speed_score,
            "composite_score": composite_score,
            "latency_ms": float(latency_ms),
            "cost": float(cost),
        }

    @classmethod
    def calculate_semantic_score(
        cls,
        candidate_output: str,
        ground_truth: str,
    ) -> float:
        """
        Calculate character-level text similarity using difflib.SequenceMatcher.

        This is a lexical similarity heuristic, not a semantic or factuality measure.
        """
        cand = (candidate_output or "").strip().lower()
        ref = (ground_truth or "").strip().lower()

        if not cand and not ref:
            return 1.0
        if not cand or not ref:
            return 0.0

        matcher = difflib.SequenceMatcher(None, cand, ref)
        return round(matcher.ratio(), 4)

    @classmethod
    def calculate_token_overlap(
        cls,
        candidate_output: str,
        ground_truth: str,
    ) -> float:
        """
        Calculate token-level Jaccard overlap score (range 0.0 to 1.0).
        """
        cand_tokens = set(re.findall(r"\w+", (candidate_output or "").lower()))
        ref_tokens = set(re.findall(r"\w+", (ground_truth or "").lower()))

        if not cand_tokens and not ref_tokens:
            return 1.0
        if not cand_tokens or not ref_tokens:
            return 0.0

        intersection = cand_tokens.intersection(ref_tokens)
        union = cand_tokens.union(ref_tokens)
        return round(len(intersection) / len(union), 4)

    @classmethod
    def calculate_format_score(
        cls,
        candidate_output: str,
        ground_truth: str,
    ) -> float:
        """
        Calculate format-adherence heuristic:
        Returns 1.0 if markdown structure and lists align with expected formatting in ground_truth,
        else 0.5.
        """
        cand = candidate_output or ""
        ref = ground_truth or ""

        # Markdown feature detections
        ref_has_code = "```" in ref
        cand_has_code = "```" in cand

        ref_has_num_list = bool(re.search(r"(?:^|\n)\s*\d+\.\s+", ref))
        cand_has_num_list = bool(re.search(r"(?:^|\n)\s*\d+\.\s+", cand))

        ref_has_bullet_list = bool(re.search(r"(?:^|\n)\s*[-*+]\s+", ref))
        cand_has_bullet_list = bool(re.search(r"(?:^|\n)\s*[-*+]\s+", cand))

        ref_has_headers = bool(re.search(r"(?:^|\n)#{1,6}\s+", ref))
        cand_has_headers = bool(re.search(r"(?:^|\n)#{1,6}\s+", cand))

        ref_has_table = bool(re.search(r"\|.+\|", ref))
        cand_has_table = bool(re.search(r"\|.+\|", cand))

        # Check alignment with expected structural elements in ground truth
        if ref_has_code and not cand_has_code:
            return 0.5

        if ref_has_num_list and not (cand_has_num_list or cand_has_bullet_list):
            return 0.5

        if ref_has_bullet_list and not (cand_has_bullet_list or cand_has_num_list):
            return 0.5

        if ref_has_headers and not cand_has_headers:
            return 0.5

        if ref_has_table and not cand_has_table:
            return 0.5

        return 1.0

    def calculate_speed_score(self, latency_ms: float) -> float:
        """
        Calculate latency speed score normalized against max_latency_ms (range 0.0 to 1.0).
        Faster latency produces a higher score.
        """
        if not math.isfinite(latency_ms) or latency_ms < 0:
            raise ValueError("latency_ms must be a finite non-negative number.")
        if latency_ms == 0:
            return 1.0
        score = max(0.0, min(1.0, 1.0 - (latency_ms / self.max_latency_ms)))
        return round(score, 4)

    def benchmark_models(
        self,
        candidate_records: list[dict[str, Any]],
        ground_truth: str,
        auto_update_tier: int | None = None,
    ) -> list[dict[str, Any]]:
        """
        Benchmark multiple candidate models, rank by composite_score, and optionally
        update the CapabilityMatrix for the given tier.

        Args:
            candidate_records: List of dicts with keys: 'model', 'output', 'latency_ms', 'cost'.
            ground_truth: Reference rubric text.
            auto_update_tier: If specified (1, 2, or 3), update the matrix with the top-scoring model.

        Returns:
            List of evaluated records ranked by composite_score in descending order.
        """
        if not ground_truth or not ground_truth.strip():
            raise ValueError("A non-empty ground-truth answer or rubric is required.")
        if auto_update_tier is not None and auto_update_tier not in (1, 2, 3):
            raise ValueError("auto_update_tier must be 1, 2, 3, or None.")
        if not candidate_records:
            raise ValueError("At least one candidate model record is required.")

        results = []
        for record in candidate_records:
            model = record.get("model")
            if not isinstance(model, str) or not model.strip():
                raise ValueError("Every candidate record must include a model identifier.")
            output = record.get("output", "")
            if not isinstance(output, str):
                raise ValueError(f"Candidate output for '{model}' must be text.")
            eval_metrics = self.evaluate_response(
                candidate_output=output,
                ground_truth=ground_truth,
                latency_ms=record.get("latency_ms", 0.0),
                cost=record.get("cost", 0.0),
            )
            result = dict(record)
            result.update(eval_metrics)
            results.append(result)

        results.sort(key=lambda r: r.get("composite_score", 0.0), reverse=True)

        if auto_update_tier is not None and results:
            best_model = results[0]["model"]
            self.capability_matrix.update_matrix(auto_update_tier, best_model)

        return results

    def benchmark_absa_lda_models(
        self,
        candidate_records: list[dict[str, Any]],
        ground_truth: str,
        auto_update_tier: int | None = None,
    ) -> list[dict[str, Any]]:
        """Score responses against the ABSA/LDA evaluation dimensions.

        The five equally weighted dimensions are dual-concept coverage,
        technical-pipeline completeness, lexical reference similarity,
        structural formatting, and cost/latency trade-off. These deterministic
        text checks measure rubric coverage, not factual correctness.
        """
        if not candidate_records:
            raise ValueError("At least one candidate model record is required.")
        if auto_update_tier is not None and auto_update_tier not in (1, 2, 3):
            raise ValueError("auto_update_tier must be 1, 2, 3, or None.")

        evaluated = self.benchmark_models(candidate_records, ground_truth)
        highest_cost = max(record["cost"] for record in evaluated)

        for record in evaluated:
            text = re.sub(r"[-‐‑‒–—]", " ", record["output"].lower())
            absa_coverage = self._coverage_score(
                text,
                (
                    (r"\babsa\b", r"\baspect based sentiment analysis\b", r"\baspect level sentiment analysis\b"),
                    (r"\baspects?\b", r"\bentities\b", r"\bnoun phrases?\b"),
                    (r"\bsentiment\b", r"\bpolarit(?:y|ies)\b"),
                ),
            )
            lda_coverage = self._coverage_score(
                text,
                (
                    (r"\blda\b", r"\blatent dirichlet allocation\b"),
                    (r"\btopics?\b", r"\btopic word\b", r"\bword topic\b", r"\bphi\b"),
                ),
            )
            dual_concept_coverage = round((absa_coverage + lda_coverage) / 2, 4)

            preprocessing = self._coverage_score(
                text,
                (
                    (r"\btokeni[sz]\w*\b",),
                    (r"\bstop words?\b", r"\bstopword\w*\b"),
                    (r"\bpos tagging\b", r"\bpart of speech\b"),
                    (r"\blemmati[sz]\w*\b",),
                ),
            )
            aspect_extraction = self._coverage_score(
                text,
                ((r"\bnouns?\b",), (r"\bnoun phrases?\b",), (r"\bcandidate aspects?\b",)),
            )
            topic_modeling = self._coverage_score(
                text,
                (
                    (r"\blda\b", r"\blatent dirichlet allocation\b"),
                    (r"\btopic distributions?\b", r"\btopics?\b.{0,80}\bwords?\b"),
                ),
            )
            topic_mapping = self._coverage_score(
                text,
                (
                    (r"\btheta\b", r"\bθ\b", r"\bdocument topic distributions?\b"),
                    (r"\bphi\b", r"\bφ\b", r"\btopic word distributions?\b", r"\bword topic distributions?\b"),
                ),
            )
            sentiment_classification = self._coverage_score(
                text,
                (
                    (
                        r"\bpost lda\b",
                        r"\bafter lda\b",
                        r"\bonce .{0,40} extracted\b",
                        r"\bafter\b.{0,50}\bextract\w*",
                    ),
                    (r"\bcontext windows?\b", r"\bdependency parse\b", r"\bdependency trees?\b"),
                    (r"\bclassifier\b", r"\bvader\b", r"\bsvm\b", r"\btransformer\b", r"\bsentiment lexicon\b"),
                    (r"\bpositive\b",),
                    (r"\bnegative\b",),
                    (r"\bneutral\b",),
                ),
            )
            technical_pipeline = round(
                (
                    preprocessing
                    + aspect_extraction
                    + topic_modeling
                    + topic_mapping
                    + sentiment_classification
                )
                / 5,
                4,
            )
            structure = self._absa_format_score(record["output"])
            cost_score = (
                round(1.0 - record["cost"] / highest_cost, 4)
                if highest_cost > 0
                else 1.0
            )
            cost_latency_tradeoff = round(
                (cost_score + record["speed_score"]) / 2,
                4,
            )

            record.update(
                {
                    "absa_coverage": absa_coverage,
                    "lda_coverage": lda_coverage,
                    "dual_concept_coverage": dual_concept_coverage,
                    "preprocessing_completeness": preprocessing,
                    "aspect_extraction_completeness": aspect_extraction,
                    "topic_modeling_completeness": topic_modeling,
                    "topic_mapping_completeness": topic_mapping,
                    "sentiment_classification_completeness": sentiment_classification,
                    "technical_pipeline_completeness": technical_pipeline,
                    "semantic_similarity": record["content_score"],
                    "structural_formatting": structure,
                    "cost_score": cost_score,
                    "cost_latency_tradeoff": cost_latency_tradeoff,
                    "absa_lda_composite_score": round(
                        (
                            dual_concept_coverage
                            + technical_pipeline
                            + record["content_score"]
                            + structure
                            + cost_latency_tradeoff
                        )
                        / 5,
                        4,
                    ),
                }
            )

        evaluated.sort(
            key=lambda record: record["absa_lda_composite_score"],
            reverse=True,
        )
        if auto_update_tier is not None:
            self.capability_matrix.update_matrix(auto_update_tier, evaluated[0]["model"])
        return evaluated

    @staticmethod
    def _coverage_score(text: str, required_groups: tuple[tuple[str, ...], ...]) -> float:
        """Return the fraction of concept groups matched by at least one alias."""
        matched = sum(
            any(re.search(pattern, text) for pattern in aliases)
            for aliases in required_groups
        )
        return round(matched / len(required_groups), 4)

    @staticmethod
    def _absa_format_score(text: str) -> float:
        """Reward a readable response organized with headings and a list."""
        normalized = text.lower()
        heading = bool(re.search(r"(?m)^\s*#{1,6}\s+\S|(?:^|\n)\s*(?:overview|pipeline|conclusion)\s*:", normalized))
        listing = bool(re.search(r"(?m)^\s*(?:[-*+]|\d+[.)])\s+\S", text))
        return round((int(heading) + int(listing)) / 2, 4)
